#[component]
pub fn Icon(name: &'static str, #[prop(default = 20.)] size: f64) -> impl IntoView {
    view! {
        <svg class="icon" width=size height=size viewBox="0 0 24 24" fill="none" stroke="currentColor"
            stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"
            inner_html=icon_path(name)></svg>
    }
}

/// Someone's photo, or a soft placeholder in their tone.
#[component]
pub fn Photo(person: Person, #[prop(default = 44.)] size: f64, #[prop(default = 14.)] radius: f64, #[prop(optional)] tall: bool) -> impl IntoView {
    let a = app();
    let uid = person.uid.clone();
    let tone = person.tone_index.rem_euclid(8);
    let h = if tall { size * 1.25 } else { size };
    let style = format!("width:{size}px;height:{h}px;border-radius:{radius}px;background:var(--tone{tone})");
    let alt = person.name.clone();
    move || match a.photo_url(&uid) {
        Some(url) => view! { <img class="photo" src=url alt=alt.clone() style=style.clone() /> }.into_any(),
        None => view! {
            <div class="photo placeholder" style=style.clone()><Icon name="user" size=size * 0.5 /></div>
        }.into_any(),
    }
}

pub fn tag(text: impl Into<String>, class: &'static str) -> impl IntoView {
    let t: String = text.into();
    view! { <span class=format!("tag {class}")>{t}</span> }
}

/// Opens a ⋯ menu at the pointer.
pub fn open_menu(ev: &web_sys::MouseEvent, kind: crate::state::MenuKind) {
    ev.stop_propagation();
    ev.prevent_default();
    let a = app();
    a.menu.set(Some(crate::state::Menu { x: ev.client_x() as f64, y: ev.client_y() as f64, kind }));
}
