"""Writes dist/sw.js, which lets the web app open with no connection, and registers it.

Run after externalise_boot.py. The worker keeps a copy of every file in the build (the page, the
WebAssembly, the scripts, fonts and icons) in a cache named after a hash of them all, so each new
build replaces the old copy in one go. Notes themselves already live in the browser (IndexedDB);
only syncing needs the network.

- The page: from the network when there is one (so updates arrive), otherwise the cached copy.
- Everything else from this site: the cached copy first. Trunk gives these hashed names, so a
  cached copy is never stale.
- Other sites (Google sign-in and Drive) are left alone.
"""
import hashlib
import json
import pathlib
import re
import sys

dist = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "dist")

# First, register it from the start-up script (the page allows no inline scripts), so the
# list of files below has the start-up script's final name.
index = (dist / "index.html").read_text()
m = re.search(r'<script type="module" src="/(boot-[0-9a-f]+\.js)"></script>', index)
if not m:
    sys.exit("Run externalise_boot.py first: no boot-*.js script in index.html")
boot = dist / m.group(1)
# The start-up script awaits the app before reaching this, so the page may have loaded already.
register = """
if ("serviceWorker" in navigator) {
  const registerWorker = () => navigator.serviceWorker.register("/sw.js", { updateViaCache: "none" }).catch(() => {});
  if (document.readyState === "complete") registerWorker(); else addEventListener("load", registerWorker);
}
"""
body = boot.read_text() + register
name = f"boot-{hashlib.sha256(body.encode()).hexdigest()[:16]}.js"
boot.unlink()
(dist / name).write_text(body)
index = index.replace(m.group(1), name)
(dist / "index.html").write_text(index)

skip = {"_headers", "sw.js"}
files = sorted(p for p in dist.rglob("*") if p.is_file() and p.name not in skip)
digest = hashlib.sha256()
for p in files:
    digest.update(p.relative_to(dist).as_posix().encode())
    digest.update(p.read_bytes())
version = digest.hexdigest()[:16]
urls = ["/"] + ["/" + p.relative_to(dist).as_posix() for p in files if p.name != "index.html"]

sw = f"""// Generated by web/scripts/make_service_worker.py. Lets Memi open without a connection.
const CACHE = "memi-{version}";
const FILES = {json.dumps(urls, indent=0)};

self.addEventListener("install", (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener("activate", (e) => {{
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("memi-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
}});

self.addEventListener("fetch", (e) => {{
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  if (req.mode === "navigate") {{
    // The page: fresh when online, so a new version arrives; the saved copy when not.
    e.respondWith(fetch(req).catch(() => caches.match("/", {{ cacheName: CACHE }})));
    return;
  }}
  e.respondWith(caches.match(req, {{ cacheName: CACHE }}).then((hit) => hit || fetch(req)));
}});
"""
(dist / "sw.js").write_text(sw)

print(f"Wrote sw.js ({len(urls)} files, cache memi-{version}) and registered it from {name}")
